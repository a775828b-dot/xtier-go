"""Write server/unicode_ranges.inc: the Unicode properties the tokenizer's pre-tokenizer regex asks about.

    python3 tools/gen_unicode.py server/unicode_ranges.inc

One entry per run of code points with the same flags (general category groups and White_Space). The regex of
Hugging Face tokenizers runs in Oniguruma, whose \\s is White_Space; the categories come from this Python's
unicodedata (Unicode version written into the file).
"""
import sys
import unicodedata

WHITE_SPACE = {0x09, 0x0A, 0x0B, 0x0C, 0x0D, 0x20, 0x85, 0xA0, 0x1680, *range(0x2000, 0x200B), 0x2028, 0x2029,
               0x202F, 0x205F, 0x3000}


def flags(cp):
    cat = unicodedata.category(chr(cp))
    f = 0
    if cat in ('Lu', 'Lt'):
        f |= 1
    elif cat == 'Ll':
        f |= 2
    elif cat in ('Lm', 'Lo'):
        f |= 4
    elif cat[0] == 'M':
        f |= 8
    elif cat[0] == 'N':
        f |= 16
    if cp in WHITE_SPACE:
        f |= 32
    return f


def main(out):
    runs, prev = [], None
    for cp in range(0x110000):
        f = flags(cp)
        if f != prev:
            runs.append((cp, f))
            prev = f
    with open(out, 'w', newline='\n') as o:
        o.write(f'// Generated by tools/gen_unicode.py (Unicode {unicodedata.unidata_version}); do not edit.\n')
        o.write('// {first code point of a run, flags}: 1 Lu/Lt, 2 Ll, 4 Lm/Lo, 8 M, 16 N, 32 White_Space\n')
        for i in range(0, len(runs), 6):
            o.write(' '.join(f'{{0x{cp:X}, {f}}},' for cp, f in runs[i:i + 6]) + '\n')
    print(out, len(runs), 'runs')


if __name__ == '__main__':
    main(sys.argv[1])
